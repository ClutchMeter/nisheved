export function chapterWords(ch: Chapter): number {
  const texts: string[] = [];
  ch.blocks.forEach((b) => {
    if (b.text) texts.push(b.text);
    if (b.items) texts.push(...b.items);
    if (b.rows) b.rows.forEach((r) => texts.push(r[0], r[1]));
  });
  return texts.join(" ").split(/\s+/).filter(Boolean).length;
}

export function serializeChapter(ch: Chapter, index: number): string {
  const lines: string[] = [`ГЛАВА ${index + 1}. ${ch.title.toUpperCase()}`];
  ch.blocks.forEach((b) => {
    switch (b.kind) {
      case "lead":
      case "p":
        lines.push("", b.text ?? "");
        break;
      case "h":
        lines.push("", `— ${b.text}`);
        break;
      case "list":
        (b.items ?? []).forEach((i) => lines.push(`• ${i}`));
        break;
      case "num":
        (b.items ?? []).forEach((i, k) => lines.push(`${k + 1}. ${i}`));
        break;
      case "tip":
        lines.push("", `[СОВЕТ] ${b.text}`);
        break;
      case "warn":
        lines.push("", `[НЮАНС НИШИ] ${b.text}`);
        break;
      case "quote":
        lines.push("", `«${b.text}»`);
        break;
      case "table":
        lines.push("", `${b.head?.[0] ?? ""} | ${b.head?.[1] ?? ""}`);
        (b.rows ?? []).forEach((r) => lines.push(`${r[0]} — ${r[1]}`));
        break;
    }
  });
  return lines.join("\n");
}

